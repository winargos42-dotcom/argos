def cloudflare_task():
    """Cloudflare: мониторит туннели и CF Workers."""
    ts = datetime.now().strftime("%H:%M")
    
    # Проверяем реальные CF туннели
    results = {}
    for host, url in [
        ("ha.argosssss.win", "https://ha.argosssss.win/"),
        ("brain-laptop", "https://brain-laptop.argosssss.win/health"),
        ("api-laptop", "https://api-laptop.argosssss.win/"),
    ]:
        try:
            req = urllib.request.Request(url)
            with urllib.request.urlopen(req, timeout=5) as r:
                results[host] = f"{r.status} ✅"
        except urllib.error.HTTPError as e:
            results[host] = f"{e.code} ⚠️"
        except Exception as e:
            results[host] = f"ERR ❌"
    
    # Проверяем cloudflared процесс
    cf_status = run_cmd("systemctl is-active cloudflared")
    
    report = (f"☁️ Клауд [{ts}] CF статус:\n"
              f"cloudflared: {cf_status.strip()}\n"
              + "\n".join(f"{h}: {s}" for h, s in results.items()))
    
    send_to_group("argos_cloudflare_bot", report)
    write_obsidian("entities/memory/cloudflare.md", report)
    return report

# ── ГЛАВНЫЙ ЦИКЛ ──────────────────────────────────────────────────────

ENTITY_TASKS = {
    "claude": claude_task,
    "kimi": kimi_task,
    "deepseek": deepseek_task,
    "gemini": gemini_task,
    "openai": openai_task,
    "cloudflare": cloudflare_task,
}

def main():
    print(f"Entity Task Runner запущен | интервал {INTERVAL}с")
    
    cycle = 0
    while True:
        cycle += 1
        ts = datetime.now().strftime("%H:%M:%S")
        print(f"\n[{ts}] Цикл #{cycle}")
        
        for entity, task_fn in ENTITY_TASKS.items():
            try:
                result = task_fn()
                print(f"  ✅ {entity}: {result[:80]}")
            except Exception as e:
                print(f"  ❌ {entity}: {e}")
        
        time.sleep(INTERVAL)

if __name__ == "__main__":
    main()
